#!/usr/bin/env python3
#
# frank-kickstart - the welcome screen's board picture as a C header:
# a PNG with alpha, scaled, reduced to up to 47 colours (index 0 is
# see-through), run-length coded.
#
#   tools/mkboardart.py IN.png src/ui/board_art.h [--width 240] [--colors 47]
#
# Stream (PackBits, row after row): c < 128: c+1 literal indices follow;
# c >= 128: c-125 copies of the next index.
# Soft edges are blended into MATTE (the welcome sky near the horizon).
#
# SPDX-License-Identifier: GPL-3.0-or-later
import argparse

from PIL import Image

MATTE = (0x2A, 0x10, 0x48)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("output")
    ap.add_argument("--width", type=int, default=240)
    ap.add_argument("--colors", type=int, default=47)
    a = ap.parse_args()

    im = Image.open(a.input).convert("RGBA")
    box = im.getchannel("A").point(lambda v: 255 if v > 16 else 0).getbbox()
    im = im.crop(box)
    h = round(im.height * a.width / im.width)
    im = im.resize((a.width, h), Image.LANCZOS)
    alpha = im.getchannel("A")
    rgb = Image.composite(im.convert("RGB"), Image.new("RGB", im.size, MATTE), alpha)
    q = rgb.quantize(colors=a.colors, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[: 3 * a.colors]
    px = q.load()
    ap_ = alpha.load()
    idx = []
    for y in range(h):
        for x in range(a.width):
            idx.append(0 if ap_[x, y] < 100 else px[x, y] + 1)
    # PackBits: c < 128: c+1 literal bytes follow; c >= 128: a run of
    # c-125 (3..130) copies of the next byte
    rle = bytearray()
    i, lit = 0, []
    def flush():
        while lit:
            chunk = lit[:128]
            del lit[:128]
            rle.append(len(chunk) - 1)
            rle.extend(chunk)
    while i < len(idx):
        n = 1
        while i + n < len(idx) and idx[i + n] == idx[i] and n < 130:
            n += 1
        if n >= 3:
            flush()
            rle += bytes((n + 125, idx[i]))
            i += n
        else:
            lit.append(idx[i])
            i += 1
    flush()
    with open(a.output, "w") as f:
        f.write("/* Generated by tools/mkboardart.py from %s. Do not edit. */\n" % a.input.split("/")[-1])
        f.write("#define BOARD_ART_W %d\n#define BOARD_ART_H %d\n#define BOARD_ART_COLORS %d\n\n"
                % (a.width, h, a.colors))
        f.write("static const uint32_t board_art_palette[%d] = {\n" % (a.colors + 1))
        cols = ["0x000000"] + ["0x%02X%02X%02X" % tuple(pal[3 * k:3 * k + 3]) for k in range(a.colors)]
        for k in range(0, len(cols), 8):
            f.write("    " + ", ".join(cols[k:k + 8]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint8_t board_art_rle[%d] = {\n" % len(rle))
        for k in range(0, len(rle), 24):
            f.write("    " + ",".join("0x%02x" % b for b in rle[k:k + 24]) + ",\n")
        f.write("};\n")
    print("%s: %dx%d, %d colours, %d bytes RLE (raw %d)" % (a.output, a.width, h, a.colors, len(rle), a.width * h))


if __name__ == "__main__":
    main()
