#!/usr/bin/env python3
#
# frank-kickstart - bitmap font generator.
#
# Rasterises a TrueType font (FreeType, through Pillow) into a 4-bit
# anti-aliased proportional font as a C header for src/gfx/font.c:
#
#   tools/mkfont.py FONT.ttf SIZE NAME OUT.h [--ranges 32-126,0x410-0x44f]
#                   [--gamma 1.0] [--tracking 0]
#
# Each glyph keeps only its ink box: width/height, offset from the pen
# position on the baseline, and the advance in 1/16 pixel. Pixels are 4-bit
# coverage, two to a byte (high nibble first), each row starting on a byte.
#
# SPDX-License-Identifier: GPL-3.0-or-later
import argparse
import sys

from PIL import Image, ImageDraw, ImageFont


def parse_ranges(text):
    cps = []
    for part in text.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part[1:]:
            a, b = part.split("-", 1) if not part.startswith("-") else (part, part)
            cps.extend(range(int(a, 0), int(b, 0) + 1))
        else:
            cps.append(int(part, 0))
    return sorted(set(cps))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("font")
    ap.add_argument("size", type=int)
    ap.add_argument("name")
    ap.add_argument("out")
    ap.add_argument("--ranges", default="32-126")
    ap.add_argument("--gamma", type=float, default=1.0,
                    help="coverage exponent (<1 makes thin strokes heavier)")
    ap.add_argument("--tracking", type=float, default=0.0,
                    help="extra advance per glyph, in pixels")
    a = ap.parse_args()

    font = ImageFont.truetype(a.font, a.size)
    ascent, descent = font.getmetrics()
    cps = [cp for cp in parse_ranges(a.ranges)]

    glyphs = []
    bitmap = bytearray()
    missing = []
    for cp in cps:
        ch = chr(cp)
        # glyphs the font does not have come out as .notdef; skip them
        if cp != 32 and font.getmask(ch).getbbox() is None:
            missing.append(cp)
            continue
        adv16 = int(round((font.getlength(ch) + a.tracking) * 16))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            px = img.load()
            # trim empty rows/columns FreeType's box may carry
            for y in range(h):
                row = []
                for x in range(w):
                    v = px[x, y] / 255.0
                    if a.gamma != 1.0 and v > 0:
                        v = v ** a.gamma
                    row.append(min(15, int(v * 15 + 0.5)))
                if len(row) & 1:
                    row.append(0)
                for i in range(0, len(row), 2):
                    bitmap.append(row[i] << 4 | row[i + 1])
        glyphs.append((cp, w, h, x0, y0, adv16, off))
        if w > 255 or h > 255 or not (-128 <= x0 < 128) or not (-128 <= y0 < 128):
            sys.exit("glyph U+%04X too large" % cp)

    if len(bitmap) >= 1 << 24:
        sys.exit("bitmap too large")

    with open(a.out, "w") as f:
        f.write("/* Generated by tools/mkfont.py from %s at %d px. Do not edit.\n"
                % (a.font.split("/")[-1], a.size))
        f.write(" * The font is licensed under the SIL Open Font License 1.1 (fonts/OFL.txt). */\n")
        f.write('#include "font.h"\n\n')
        f.write("static const uint8_t %s_bitmap[%d] = {\n" % (a.name, len(bitmap)))
        for i in range(0, len(bitmap), 24):
            f.write("    " + ",".join("0x%02x" % b for b in bitmap[i:i + 24]) + ",\n")
        f.write("};\n\n")
        f.write("static const font_glyph_t %s_glyphs[%d] = {\n" % (a.name, len(glyphs)))
        for cp, w, h, x0, y0, adv16, off in glyphs:
            f.write("    {0x%04x, %d, %d, %d, %d, %d, %d},\n" % (cp, w, h, x0, y0, adv16, off))
        f.write("};\n\n")
        f.write("const font_t %s = {\n" % a.name)
        f.write("    .ascent = %d, .descent = %d, .line_h = %d,\n"
                % (ascent, descent, int(round(a.size * 1.35))))
        f.write("    .nglyphs = %d, .glyphs = %s_glyphs, .bitmap = %s_bitmap,\n};\n"
                % (len(glyphs), a.name, a.name))
    print("%s: %d glyphs, %d bitmap bytes, %d table bytes%s" % (
        a.name, len(glyphs), len(bitmap), len(glyphs) * 12,
        (", missing " + " ".join("U+%04X" % c for c in missing)) if missing else ""))


if __name__ == "__main__":
    main()
